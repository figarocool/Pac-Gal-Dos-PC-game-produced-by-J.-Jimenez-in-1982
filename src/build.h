static inline void maze_cell(MazePainter *p,unsigned row,unsigned col,unsigned ch,unsigned attr) {
 unsigned index=p->written++;
 if(p->game&&index>=p->first&&index<p->last&&row<p->rows) {
  p->game->ch[row][col]=(unsigned char)ch;
  p->game->attr[row][col]=(unsigned char)attr;
 }
}
static inline void maze_stroke(MazePainter *p,unsigned row,unsigned col,unsigned width,
                               unsigned first,unsigned second,unsigned attr) {
 for(unsigned i=0;i<width;i++)maze_cell(p,row,col+i,i%2?second:first,attr);
}
static inline void maze_caption(MazePainter *p,unsigned row,unsigned col,const char *text,unsigned attr) {
 for(;*text;text++,col++)maze_cell(p,row,col,(unsigned char)*text,attr);
}
